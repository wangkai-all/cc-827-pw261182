def parse_time_value(x: Any) -> float:
    if is_finite_number(x):
        return float(x)
    if not isinstance(x, str):
        raise ValueError(f"Unsupported time value: {x!r}")
    s = x.strip()
    try:
        return float(s)
    except ValueError:
        pass
    ss = s.replace("Z", "+00:00")
    try:
        dt = datetime.fromisoformat(ss)
        if dt.tzinfo is None:
            dt = dt.replace(tzinfo=None)
        return dt.timestamp() / 3600.0
    except ValueError as e:
        raise ValueError(f"Cannot parse time {x!r}; use number or ISO datetime") from e


def _raw_time(x: Dict[str, Any]) -> Any:
    for key in ("t", "time", "timestamp", "datetime", "date", "ts"):
        if key in x and x[key] is not None:
            return x[key]
    raise ValueError("Event is missing a time/t/timestamp field")


def _raw_category(x: Dict[str, Any]) -> str:
    for key in ("category", "cat", "type", "class", "label", "event_type"):
        if key in x and x[key] is not None:
            return str(x[key])
    return "event"


def merge_windows(windows: Sequence[Tuple[float, float]]) -> List[Tuple[float, float]]:
    vals = [(float(a), float(b)) for a, b in windows if b > a]
    if not vals:
        return []
    vals.sort()
    out = [vals[0]]
    for a, b in vals[1:]:
        pa, pb = out[-1]
        if a <= pb:
            out[-1] = (pa, max(pb, b))
        else:
            out.append((a, b))
    return out


def prepare_dataset(raw: Dict[str, Any], selected_categories: Optional[Sequence[str]] = None) -> Dict[str, Any]:
    """Parse and validate a JSON-like dataset.

    Numeric datasets retain their supplied time unit.  ISO timestamps are
    converted to hours relative to the earliest supplied time/window boundary.
    """
    raw_events = raw.get("events", [])
    if not isinstance(raw_events, list) or not raw_events:
        raise ValueError("Dataset must contain a non-empty events array")

    parsed_raw_times = [parse_time_value(_raw_time(e)) for e in raw_events]
    iso_like = any(isinstance(_raw_time(e), str) and _looks_iso(_raw_time(e)) for e in raw_events)
    raw_windows = raw.get("windows") or []
    parsed_window_times = []
    for w in raw_windows:
        if isinstance(w, dict):
            parsed_window_times.extend([parse_time_value(w.get("start")), parse_time_value(w.get("end"))])
        elif isinstance(w, (list, tuple)) and len(w) == 2:
            parsed_window_times.extend([parse_time_value(w[0]), parse_time_value(w[1])])

    origin = min(parsed_raw_times + parsed_window_times) if iso_like else 0.0
    scale = 1.0 if iso_like else 1.0  # ISO parser already returns hours.

    def coord(v: Any) -> float:
        return (parse_time_value(v) - origin) * scale if iso_like else parse_time_value(v)

    categories_all = raw.get("categories")
    if categories_all:
        categories_all = [str(c) for c in categories_all]
    else:
        categories_all = sorted({_raw_category(e) for e in raw_events})

    if selected_categories is not None:
        wanted = {str(c) for c in selected_categories}
        categories = [c for c in categories_all if c in wanted]
        if not categories:
            raise ValueError("At least one event category must be selected")
    else:
        categories = list(categories_all)

    cat_index = {c: i for i, c in enumerate(categories)}
    events: List[Dict[str, Any]] = []
    for e in raw_events:
        cat = _raw_category(e)
        if cat not in cat_index:
            continue
        events.append({"t": coord(_raw_time(e)), "category": cat, "ci": cat_index[cat]})
    events.sort(key=lambda e: (e["t"], e["ci"]))
    for i, e in enumerate(events):
        e["index"] = i
    if not events:
        raise ValueError("No events remain after category filtering")

    windows: List[Tuple[float, float]] = []
    for w in raw_windows:
        if isinstance(w, dict):
            a, b = coord(w.get("start")), coord(w.get("end"))
        else:
            a, b = coord(w[0]), coord(w[1])
        if b > a:
            windows.append((a, b))

    if not windows:
        # Explicitly conservative fallback.  It is flagged in diagnostics and
        # is not equivalent to knowing the true observation window.
        windows = [(events[0]["t"], events[-1]["t"] + 1e-9)]
        window_source = "inferred_event_span"
    else:
        window_source = "imported"
    windows = merge_windows(windows)

    history_start = raw.get("history_start")
    hs = coord(history_start) if history_start is not None else None

    active_duration = sum(b - a for a, b in windows)
    span_start = windows[0][0]
    span_end = windows[-1][1]
    calendar_span = span_end - span_start
    gaps = [(windows[i][1], windows[i + 1][0]) for i in range(len(windows) - 1) if windows[i + 1][0] > windows[i][1]]
    gap_duration = sum(b - a for a, b in gaps)

    resolution = raw.get("resolution")
    if resolution is not None:
        resolution = float(resolution)
    else:
        resolution = infer_resolution([e["t"] for e in events])

    rounding = resolution_diagnostics(events, resolution)
    data = {
        "categories": categories,
        "all_categories": categories_all,
        "events": events,
        "windows": windows,
        "gaps": gaps,
        "history_start": hs,
        "time_unit": raw.get("time_unit", "hour" if iso_like else "time unit"),
        "time_origin": datetime.fromtimestamp(origin * 3600).isoformat() if iso_like else raw.get("time_origin"),
        "active_duration": active_duration,
        "calendar_span": calendar_span,
        "gap_duration": gap_duration,
        "coverage": active_duration / calendar_span if calendar_span > 0 else 1.0,
        "window_source": window_source,
        "resolution": resolution,
        "rounding": rounding,
        "name": raw.get("name", "event-sequence"),
        "description": raw.get("description", ""),
    }
    annotate_window_membership(data)
    return data


def _looks_iso(x: Any) -> bool:
    return isinstance(x, str) and ("-" in x and ":" in x)


def infer_resolution(times: Sequence[float]) -> Optional[float]:
    vals = sorted(set(float(t) for t in times))
    if len(vals) < 2:
        return None
    gaps = [vals[i + 1] - vals[i] for i in range(len(vals) - 1) if vals[i + 1] > vals[i]]
    if not gaps:
        return None
    q = min(gaps)
    # Refine when the minimum observed gap is a multiple of decimal rounding.
    # The smallest adjacent gap is a safe observable resolution bound.
    return q if q > 0 else None


def resolution_diagnostics(events: Sequence[Dict[str, Any]], resolution: Optional[float]) -> Dict[str, Any]:
    times = [e["t"] for e in events]
    counts: Dict[float, int] = {}
    for t in times:
        counts[t] = counts.get(t, 0) + 1
    max_batch = max(counts.values()) if counts else 0
    tied_extra = sum(c - 1 for c in counts.values() if c > 1)
    gaps = [times[i + 1] - times[i] for i in range(len(times) - 1)]
    positive_gaps = [g for g in gaps if g > 1e-12]
    med_gap = median(positive_gaps) if positive_gaps else 0.0
    return {
        "resolution": resolution,
        "distinct_times": len(counts),
        "max_batch": max_batch,
        "tied_events": tied_extra,
        "tie_rate": tied_extra / len(events) if events else 0.0,
        "median_positive_gap": med_gap,
        "resolution_to_median_gap": resolution / med_gap if resolution and med_gap > 0 else None,
    }


def annotate_window_membership(data: Dict[str, Any]) -> None:
    windows = data["windows"]

    def inside(t: float) -> bool:
        return any(a <= t <= b for i, (a, b) in enumerate(windows))

    for e in data["events"]:
        e["in_window"] = inside(e["t"])


def make_scope(
    data: Dict[str, Any],
    lo: Optional[float] = None,
    hi: Optional[float] = None,
    include_lo: Optional[bool] = None,
    include_hi: bool = True,
) -> Dict[str, Any]:
    """Clip a prepared dataset to a training or holdout time scope.

    Imported observation windows are closed at both ends.  When ``lo`` is
    supplied explicitly as an artificial train/holdout cut, an event exactly at
    that cut belongs to the training side and is excluded from the lower scope,
    preventing double counting.
    """
    explicit_lo = lo is not None
    lo = data["windows"][0][0] if lo is None else lo
    hi = data["windows"][-1][1] if hi is None else hi
    if include_lo is None:
        include_lo = not explicit_lo
    wins = merge_windows([(max(a, lo), min(b, hi)) for a, b in data["windows"] if min(b, hi) > max(a, lo)])
    evs = [dict(e) for e in data["events"] if any(a <= e["t"] <= b for a, b in wins)]
    if not include_lo:
        evs = [e for e in evs if e["t"] != lo]
    if not include_hi:
        evs = [e for e in evs if e["t"] != hi]
    active = sum(b - a for a, b in wins)
    return {
        **{k: v for k, v in data.items() if k not in ("events", "windows", "active_duration", "gaps", "coverage")},
        "events": evs,
        "windows": wins,
        "gaps": [(wins[i][1], wins[i + 1][0]) for i in range(len(wins) - 1)],
        "active_duration": active,
        "calendar_span": wins[-1][1] - wins[0][0] if wins else 0.0,
        "coverage": active / (wins[-1][1] - wins[0][0]) if wins and wins[-1][1] > wins[0][0] else 1.0,
        "parent_data": data,
    }


def split_time_by_exposure(data: Dict[str, Any], frac: float = 0.7) -> float:
    total = data["active_duration"]
    target = total * frac
    used = 0.0
    for a, b in data["windows"]:
        d = b - a
        if used + d >= target:
            return a + (target - used)
        used += d
    return data["windows"][-1][1]


def equal_exposure_cuts(windows: Sequence[Tuple[float, float]], bins: int) -> List[float]:
    total = sum(b - a for a, b in windows)
    cuts = []
    for r in range(1, bins):
        target = total * r / bins
        used = 0.0
        for a, b in windows:
            if used + (b - a) >= target:
                cuts.append(a + target - used)
                break
            used += b - a
    return cuts



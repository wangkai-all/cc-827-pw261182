def evaluate_holdout(
    fit: Dict[str, Any],
    holdout: Dict[str, Any],
    initial_time: Optional[float] = None,
) -> Dict[str, Any]:
    model: ModelSpec = fit["spec"]
    pspec, maps = fit["pspec"], fit["maps"]
    params = fit["params"]
    gap_correction = fit.get("gap_correction", True)
    initial_state = list(fit["final_state"]) if fit.get("final_state") is not None else None

    # fit["final_state"] is timestamped at the training scope's last window
    # endpoint.  An exposure split can land exactly on that endpoint while the
    # first holdout window starts after an inter-window gap.  The per-window
    # loops only relax gaps between windows inside the holdout scope, so relax
    # this train->holdout gap once here and share the result with likelihood,
    # residual, and count paths.
    state_time = initial_time
    if state_time is None:
        state_time = fit.get("final_state_time")
    if initial_state is not None and holdout.get("windows") and state_time is not None:
        first_a = holdout["windows"][0][0]
        if first_a > float(state_time) + 1e-12:
            gap_start = float(state_time)
            gap_end = first_a
            if gap_correction:
                bounds = [gap_start] + [c for c in model.cuts if gap_start < c < gap_end] + [gap_end]
                for x, y in zip(bounds[:-1], bounds[1:]):
                    rr = model.bg_index((x + y) / 2.0)
                    ok = _relax_gap(
                        initial_state,
                        None,
                        y - x,
                        params["mu"],
                        params["eta"],
                        params["beta"],
                        maps,
                        len(pspec),
                        rr,
                    )
                    if not ok:
                        _decay_state(initial_state, None, y - x, params["beta"], maps["beta"])
            else:
                _decay_state(initial_state, None, gap_end - gap_start, params["beta"], maps["beta"])

    # Initialize holdout with the exact training-end state.  No stationary
    # reset: the training history is real observed conditioning information.
    out = likelihood(
        params,
        holdout,
        model,
        pspec,
        maps,
        want_grad=False,
        initial_m=initial_state,
        boundary="observed",
        gap_correction=gap_correction,
        return_trace=True,
    )
    rows = out["event_rows"] or []
    residual_rows = time_rescaling_residuals(params, holdout, model, pspec, maps, initial_state, gap_correction)
    residual_values = [r["residual"] for r in residual_rows if r["residual"] is not None]
    residual_tests = residual_diagnostics(residual_values)
    counts = count_diagnostics(params, holdout, model, pspec, maps, initial_state, gap_correction)
    return {
        "loglik": out["loglik"],
        "events": len(holdout["events"]),
        "loglik_per_event": out["loglik"] / max(len(holdout["events"]), 1),
        "rows": rows,
        "residual_rows": residual_rows,
        "residuals": residual_values,
        "residual_tests": residual_tests,
        "counts": counts,
        "final_state": out.get("final_state"),
    }


def time_rescaling_residuals(
    params,
    scope,
    model: ModelSpec,
    pspec,
    maps,
    initial_m,
    gap_correction: bool,
) -> List[Dict[str, Any]]:
    """Integrated total intensity between consecutive events in one window."""
    k = model.k
    mu, eta, beta = params["mu"], params["eta"], params["beta"]
    rows = []
    m = list(initial_m) if initial_m is not None else [0.0] * model.state_size
    windows = scope["windows"]
    events = scope["events"]
    ev_pos = 0
    for wi, (a, b) in enumerate(windows):
        if wi > 0:
            pa, pb = windows[wi - 1]
            if gap_correction:
                bounds = [pb] + [c for c in model.cuts if pb < c < a] + [a]
                cur = pb
                for x, y in zip(bounds[:-1], bounds[1:]):
                    rr = model.bg_index((x + y) / 2)
                    _relax_gap(m, None, y - x, mu, eta, beta, maps, len(pspec), rr)
            else:
                _decay_state(m, None, a - pb, beta, maps["beta"])
        # advance to window
        while ev_pos < len(events) and events[ev_pos]["t"] < a:
            ev_pos += 1
        win_events = []
        j = ev_pos
        while j < len(events) and a <= events[j]["t"] <= b:
            win_events.append(events[j])
            j += 1
        cursor = a
        hazard = 0.0
        have_previous_event = False
        for e in win_events:
            t = e["t"]
            # If this is the first event after a window boundary, the interval
            # is left-censored and cannot be used as a complete Exp residual.
            usable = have_previous_event
            tied_batch_member = usable and abs(t - cursor) <= 1e-10
            bounds = [cursor] + [c for c in model.cuts if cursor < c < t] + [t]
            for x, y in zip(bounds[:-1], bounds[1:]):
                if y <= x:
                    continue
                dt = y - x
                rr = model.bg_index((x + y) / 2)
                total_bg = sum(mu[ci][rr] for ci in range(k))
                hazard += total_bg * dt
                gamma2 = model.kernel_shape == "gamma2"
                for target in range(k):
                    for source in range(k):
                        ai = target * k + source
                        bb = beta[target][source]
                        xx = bb * dt
                        if gamma2:
                            i0 = -math.expm1(-xx) / bb
                            i1 = (1.0 - (1.0 + xx) * math.exp(-xx)) / bb
                            hazard += m[ai] * i0 + m[k * k + ai] * i1
                        else:
                            integ = -math.expm1(-xx) / bb
                            hazard += m[ai] * integ
                _decay_state(m, None, dt, beta, maps["beta"])
            residual = hazard if usable and not tied_batch_member else None
            rows.append({"t": t, "ci": e["ci"], "residual": residual, "reason": "tied_timestamp" if tied_batch_member else None})
            # At an event, reset integrated hazard and jump.  Time-rescaling
            # increments are between successive points of the total process.
            hazard = 0.0
            have_previous_event = True
            _jump_event(e["ci"], m, None, eta, beta, maps)
            cursor = t
        ev_pos = j
        # Decay state to window end for next gap.
        bounds = [cursor] + [c for c in model.cuts if cursor < c < b] + [b]
        for x, y in zip(bounds[:-1], bounds[1:]):
            if y > x:
                _decay_state(m, None, y - x, beta, maps["beta"])
    return rows


def residual_diagnostics(z: Sequence[float]) -> Dict[str, Any]:
    zs = [x for x in z if x is not None and math.isfinite(x) and x >= 0]
    n = len(zs)
    if n < 3:
        return {"n": n, "available": False, "message": "至少需要 3 个完整事件间隔才能做残差检验"}
    mean = sum(zs) / n
    var = sum((x - mean) ** 2 for x in zs) / max(n - 1, 1)
    ks = ks_exp_uniform(zs)
    acf = acf_values(zs, min(10, max(1, n // 4)))
    lb = ljung_box(zs, min(10, max(2, n // 5)))
    qq = []
    sz = sorted(zs)
    for i, x in enumerate(sz):
        p = (i + 0.5) / n
        theoretical = -math.log(1 - p)
        qq.append({"empirical": x, "theoretical": theoretical})
    return {
        "available": True,
        "n": n,
        "mean": mean,
        "expected_mean": 1.0,
        "variance": var,
        "ks": ks,
        "acf": acf,
        "ljung_box": lb,
        "qq": qq[:: max(1, n // 120)],
        "mean_z_score": (mean - 1) / math.sqrt(1 / n),
    }


def ks_exp_uniform(z: Sequence[float]) -> Dict[str, float]:
    """KS test for Exp(1), transformed u=1-exp(-z) ~ Uniform(0,1)."""
    n = len(z)
    u = sorted(1 - math.exp(-x) for x in z)
    d = 0.0
    for i, x in enumerate(u):
        d = max(d, abs((i + 1) / n - x), abs(x - i / n))
    # Asymptotic Kolmogorov p-value.
    en = math.sqrt(n)
    lam = (en + 0.12 + 0.11 / en) * d
    p = kolmogorov_sf(lam)
    return {"statistic": d, "p_value": clamp(p, 0.0, 1.0)}


def kolmogorov_sf(x: float) -> float:
    if x < 0.27:
        return 1.0
    s = 0.0
    for k in range(1, 100):
        term = 1.0 if k % 2 else -1.0
        add = 2 * term * math.exp(-2 * k * k * x * x)
        s += add
        if abs(add) < 1e-10:
            break
    return clamp(s, 0.0, 1.0)


def acf_values(x: Sequence[float], nlags: int) -> List[Dict[str, float]]:
    n = len(x)
    mean = sum(x) / n
    denom = sum((v - mean) ** 2 for v in x) or 1.0
    out = []
    for lag in range(1, nlags + 1):
        num = sum((x[i] - mean) * (x[i + lag] - mean) for i in range(n - lag))
        out.append({"lag": lag, "acf": num / denom, "threshold": 1.96 / math.sqrt(n)})
    return out


def ljung_box(x: Sequence[float], lags: int) -> Dict[str, float]:
    n = len(x)
    acfs = acf_values(x, lags)
    q = n * (n + 2) * sum((a["acf"] ** 2) / (n - a["lag"]) for a in acfs)
    p = chi2_sf(q, lags)
    return {"statistic": q, "df": lags, "p_value": clamp(p, 0, 1)}


def count_diagnostics(params, scope, model: ModelSpec, pspec, maps, initial_m, gap_correction) -> Dict[str, Any]:
    """Observed vs compensator-expected counts in equal active-duration bins."""
    k = model.k
    bins = min(8, max(3, int(math.sqrt(max(len(scope["events"]), 9)))))
    cuts = equal_exposure_cuts(scope["windows"], bins)
    bin_model = ModelSpec(model.categories, cuts, model.beta_mode, model.kernel_shape)
    # Integrate expected intensity on a fine event/grid traversal.  We reuse
    # time_rescaling-like state but accumulate per category and bin.
    mu, eta, beta = params["mu"], params["eta"], params["beta"]
    # Background params have original r; evaluate by original model.bg_index.
    expected = [[0.0] * bins for _ in range(k)]
    observed = [[0] * bins for _ in range(k)]

    def bin_index(t: float) -> int:
        idx = 0
        for c in cuts:
            if t >= c:
                idx += 1
        return min(idx, bins - 1)

    for e in scope["events"]:
        observed[e["ci"]][bin_index(e["t"])] += 1

    m = list(initial_m) if initial_m is not None else [0.0] * model.state_size
    windows = scope["windows"]
    events = scope["events"]
    ev_pos = 0
    for wi, (a, b) in enumerate(windows):
        if wi > 0:
            pa, pb = windows[wi - 1]
            if gap_correction:
                bounds = [pb] + [c for c in model.cuts if pb < c < a] + [a]
                for x, y in zip(bounds[:-1], bounds[1:]):
                    rr = model.bg_index((x + y) / 2)
                    _relax_gap(m, None, y - x, mu, eta, beta, maps, len(pspec), rr)
            else:
                _decay_state(m, None, a - pb, beta, maps["beta"])
        while ev_pos < len(events) and events[ev_pos]["t"] < a:
            ev_pos += 1
        j = ev_pos
        while j < len(events) and a <= events[j]["t"] <= b:
            e = events[j]
            t = e["t"]
            cur = a if j == ev_pos else events[j - 1]["t"]
            # Integrate from cur to t with bin cut + bg cut boundaries.
            points = [cur, t] + [c for c in cuts + model.cuts if cur < c < t]
            points = sorted(set(points))
            for x, y in zip(points[:-1], points[1:]):
                if y <= x:
                    continue
                dt = y - x
                rr = model.bg_index((x + y) / 2)
                bb = bin_index((x + y) / 2)
                for ci in range(k):
                    expected[ci][bb] += mu[ci][rr] * dt
                    for source in range(k):
                        ai = ci * k + source
                        bbeta = beta[ci][source]
                        xx = bbeta * dt
                        if model.kernel_shape == "gamma2":
                            i0 = -math.expm1(-xx) / bbeta
                            i1 = (1.0 - (1.0 + xx) * math.exp(-xx)) / bbeta
                            expected[ci][bb] += m[ai] * i0 + m[k * k + ai] * i1
                        else:
                            expected[ci][bb] += m[ai] * (-math.expm1(-xx) / bbeta)
                _decay_state(m, None, dt, beta, maps["beta"])
            _jump_event(e["ci"], m, None, eta, beta, maps)
            j += 1
        # tail
        cur = events[j - 1]["t"] if j > ev_pos else a
        points = [cur, b] + [c for c in cuts + model.cuts if cur < c < b]
        points = sorted(set(points))
        for x, y in zip(points[:-1], points[1:]):
            if y <= x:
                continue
            dt = y - x
            rr = model.bg_index((x + y) / 2)
            bb = bin_index((x + y) / 2)
            for ci in range(k):
                expected[ci][bb] += mu[ci][rr] * dt
                for source in range(k):
                    ai = ci * k + source
                    bbeta = beta[ci][source]
                    xx = bbeta * dt
                    if model.kernel_shape == "gamma2":
                        i0 = -math.expm1(-xx) / bbeta
                        i1 = (1.0 - (1.0 + xx) * math.exp(-xx)) / bbeta
                        expected[ci][bb] += m[ai] * i0 + m[k * k + ai] * i1
                    else:
                        expected[ci][bb] += m[ai] * (-math.expm1(-xx) / bbeta)
            _decay_state(m, None, dt, beta, maps["beta"])
        ev_pos = j

    # Pearson statistic over category-bin cells with adequate expected count.
    chi = 0.0
    df = 0
    cells = []
    total_obs = 0
    total_exp = 0.0
    for ci in range(k):
        for bi in range(bins):
            o = observed[ci][bi]
            e = expected[ci][bi]
            total_obs += o
            total_exp += e
            cells.append({"category": scope["categories"][ci], "bin": bi + 1, "observed": o, "expected": e})
            if e >= 1.0:
                chi += (o - e) ** 2 / e
                df += 1
    df = max(df - 1, 1)
    p = chi2_sf(chi, df)
    by_cat = []
    for ci, name in enumerate(scope["categories"]):
        o = sum(observed[ci])
        e = sum(expected[ci])
        z = (o - e) / math.sqrt(max(e, 1e-9))
        by_cat.append({"category": name, "observed": o, "expected": e, "z": z})
    return {
        "bins": bins,
        "cells": cells,
        "chi_square": chi,
        "df": df,
        "p_value": clamp(p, 0, 1),
        "total_observed": total_obs,
        "total_expected": total_exp,
        "by_category": by_cat,
    }


def chi2_sf(x: float, df: int) -> float:
    if df <= 0 or x <= 0:
        return 1.0
    return clamp(gammaincc(df / 2.0, x / 2.0), 0.0, 1.0)


def gammaincc(a: float, x: float) -> float:
    """Regularized upper incomplete gamma via Numerical Recipes routines."""
    if x < 0:
        return 1.0
    if x < a + 1.0:
        return 1.0 - gammainc_series(a, x)
    return gammaincc_cf(a, x)


def gammainc_series(a: float, x: float) -> float:
    if x == 0:
        return 0.0
    ap = a
    term = 1.0 / a
    total = term
    for _ in range(200):
        ap += 1
        term *= x / ap
        total += term
        if abs(term) < abs(total) * 1e-12:
            break
    return total * math.exp(-x + a * math.log(x) - math.lgamma(a))


def gammaincc_cf(a: float, x: float) -> float:
    b = x + 1.0 - a
    c = 1e300
    d = 1.0 / b if abs(b) > 1e-300 else 1e-300
    h = d
    for i in range(1, 201):
        an = -i * (i - a)
        b += 2.0
        d = an * d + b
        if abs(d) < 1e-300:
            d = 1e-300
        c = b + an / c
        if abs(c) < 1e-300:
            c = 1e-300
        d = 1.0 / d
        delta = d * c
        h *= delta
        if abs(delta - 1.0) < 1e-12:
            break
    return math.exp(-x + a * math.log(x) - math.lgamma(a)) * h



@dataclass
class ModelSpec:
    categories: List[str]
    cuts: List[float]
    beta_mode: str = "pair"  # "pair" or "common"
    kernel_shape: str = "exp"  # "exp" or normalized Gamma(shape=2)

    @property
    def k(self) -> int:
        return len(self.categories)

    @property
    def r(self) -> int:
        return len(self.cuts) + 1

    @property
    def state_size(self) -> int:
        # Gamma(2) uses trigger state y2 plus one cascade/auxiliary state y1.
        return self.k * self.k * (2 if self.kernel_shape == "gamma2" else 1)

    def bg_index(self, t: float) -> int:
        idx = 0
        for c in self.cuts:
            if t >= c:
                idx += 1
        return idx

    def build_index(self) -> Tuple[List[Tuple[str, int, int]], Dict[str, Any]]:
        p = 0
        spec: List[Tuple[str, int, int]] = []
        idx_mu: List[List[int]] = [[-1] * self.r for _ in range(self.k)]
        for k in range(self.k):
            for r in range(self.r):
                idx_mu[k][r] = p
                spec.append(("mu", k, r))
                p += 1
        idx_eta = [[-1] * self.k for _ in range(self.k)]
        for k in range(self.k):
            for j in range(self.k):
                idx_eta[k][j] = p
                spec.append(("eta", k, j))
                p += 1
        idx_beta = [[-1] * self.k for _ in range(self.k)]
        if self.beta_mode == "common":
            common = p
            p += 1
            for k in range(self.k):
                for j in range(self.k):
                    idx_beta[k][j] = common
            spec.append(("beta", -1, -1))
        else:
            for k in range(self.k):
                for j in range(self.k):
                    idx_beta[k][j] = p
                    spec.append(("beta", k, j))
                    p += 1
        maps = {"mu": idx_mu, "eta": idx_eta, "beta": idx_beta}
        return spec, maps


def initial_parameters(scope: Dict[str, Any], model: ModelSpec) -> Dict[str, List[List[float]]]:
    k, r = model.k, model.r
    duration = max(scope["active_duration"], 1e-9)
    counts = [0] * k
    exposure = [0.0] * r
    for e in scope["events"]:
        counts[e["ci"]] += 1
    for a, b in scope["windows"]:
        # Exposure by background segment.
        bounds = [a] + [c for c in model.cuts if a < c < b] + [b]
        for x, y in zip(bounds[:-1], bounds[1:]):
            exposure[model.bg_index((x + y) / 2.0)] += y - x

    mu = [[0.0] * r for _ in range(k)]
    for ci in range(k):
        for rr in range(r):
            # Assume roughly 65% of events are immigrants at initialization.
            mu[ci][rr] = max(counts[ci] * 0.65 / k, 0.02) / max(exposure[rr], duration / r, 1e-6)
            if exposure[rr] <= 1e-9:
                mu[ci][rr] = max(counts[ci] * 0.65 / duration, 1e-4)

    eta = [[0.04 if i != j else 0.22 for j in range(k)] for i in range(k)]
    # Scale diagonal down if too dense.
    if sum(counts) / duration > 20:
        eta = [[x * 0.5 for x in row] for row in eta]

    positive_gaps = []
    by_cat: Dict[int, List[float]] = {i: [] for i in range(k)}
    last: Dict[int, float] = {}
    for e in scope["events"]:
        ci = e["ci"]
        if ci in last:
            by_cat[ci].append(e["t"] - last[ci])
        last[ci] = e["t"]
        positive_gaps.append(e["t"])
    med = median([g for vals in by_cat.values() for g in vals if g > 1e-9])
    if med <= 1e-9:
        allg = []
        ts = [e["t"] for e in scope["events"]]
        for i in range(1, len(ts)):
            if ts[i] > ts[i - 1]:
                allg.append(ts[i] - ts[i - 1])
        med = median(allg)
    beta0 = 1.0 / med if med > 1e-9 else 1.0 / max(scope["calendar_span"] / 20.0, 1e-3)
    beta0 = clamp(beta0, 1e-3, 50.0)
    beta = [[beta0 for _ in range(k)] for _ in range(k)]
    return {"mu": mu, "eta": eta, "beta": beta, "beta0": beta0}


def pack_params(params: Dict[str, Any], spec: ModelSpec, pspec: List[Tuple[str, int, int]], maps: Dict[str, Any]) -> List[float]:
    q = [0.0] * len(pspec)
    for p, (kind, i, j) in enumerate(pspec):
        if kind == "mu":
            q[p] = math.log(max(params["mu"][i][j], 1e-10))
        elif kind == "eta":
            q[p] = math.log(max(params["eta"][i][j], 1e-10))
        else:
            q[p] = math.log(max(params["beta"][i][j] if i >= 0 else params["beta"][0][0], 1e-10))
    return q


def unpack_q(q: Sequence[float], spec: ModelSpec, pspec: List[Tuple[str, int, int]]) -> Dict[str, List[List[float]]]:
    mu = [[0.0] * spec.r for _ in range(spec.k)]
    eta = [[0.0] * spec.k for _ in range(spec.k)]
    beta = [[0.0] * spec.k for _ in range(spec.k)]
    for p, (kind, i, j) in enumerate(pspec):
        val = math.exp(float(q[p]))
        if kind == "mu":
            mu[i][j] = val
        elif kind == "eta":
            eta[i][j] = val
        else:
            if i < 0:
                for a in range(spec.k):
                    for b in range(spec.k):
                        beta[a][b] = val
            else:
                beta[i][j] = val
    return {"mu": mu, "eta": eta, "beta": beta}


def _decay_state(
    m: List[float],
    s: Optional[List[List[float]]],
    dt: float,
    beta: Sequence[Sequence[float]],
    idx_beta: Sequence[Sequence[int]],
) -> None:
    k = len(beta)
    n = k * k
    gamma2 = len(m) == 2 * n
    for a in range(n):
        target = a // k
        j = a % k
        b = beta[target][j]
        x = b * dt
        f = math.exp(-x)
        old_b = m[a]
        if gamma2:
            ai_aux = n + a
            old_a = m[ai_aux]
            g = x * f
            m[a] = old_b * f + g * old_a
            m[ai_aux] = old_a * f
        else:
            m[a] = old_b * f
        if s is not None:
            row = s[a]
            qb = idx_beta[target][j]
            if gamma2:
                row_aux = s[n + a]
                old_row_b = row[:]
                old_row_a = row_aux[:]
                g = x * f
                for p in range(len(row)):
                    row[p] = f * old_row_b[p] + g * old_row_a[p]
                    row_aux[p] = f * old_row_a[p]
                # Explicit derivatives with q=log(beta).
                row[qb] += -old_b * x * f + old_a * x * f * (1.0 - x)
                row_aux[qb] += -old_a * x * f
            else:
                for p in range(len(row)):
                    row[p] *= f
                # d(old*exp(-beta dt))/d log beta, plus existing derivative.
                row[qb] += -old_b * dt * b * f


def _interval_compensator(
    m: Sequence[float],
    s: Optional[List[List[float]]],
    dt: float,
    mu: Sequence[Sequence[float]],
    r: int,
    eta: Sequence[Sequence[float]],
    beta: Sequence[Sequence[float]],
    maps: Dict[str, Any],
    ll: float,
    g: Optional[List[float]],
) -> float:
    k = len(mu)
    n = k * k
    gamma2 = len(m) == 2 * n
    idx_mu = maps["mu"]
    idx_beta = maps["beta"]
    for ci in range(k):
        val = mu[ci][r] * dt
        ll -= val
        if g is not None:
            g[idx_mu[ci][r]] -= val
    for target in range(k):
        for source in range(k):
            ai = target * k + source
            b = beta[target][source]
            x = b * dt
            f = math.exp(-x)
            if gamma2:
                ai_aux = n + ai
                # Integrals of B(s) and A*beta*s*exp(-beta*s), respectively.
                i0 = -math.expm1(-x) / b if b > 0 else dt
                i1 = (1.0 - (1.0 + x) * f) / b if b > 0 else 0.5 * dt * x
                val = m[ai] * i0 + m[ai_aux] * i1
                ll -= val
                if g is not None and s is not None:
                    row_b, row_a = s[ai], s[ai_aux]
                    for p in range(len(g)):
                        g[p] -= row_b[p] * i0 + row_a[p] * i1
                    d_i0_logb = ((1.0 + x) * f - 1.0) / b
                    j1 = 1.0 - (1.0 + x) * f
                    d_i1_logb = (x * x * f - j1) / b
                    qb = idx_beta[target][source]
                    g[qb] -= m[ai] * d_i0_logb + m[ai_aux] * d_i1_logb
            else:
                integ = -math.expm1(-x) / b if b > 0 else dt
                ll -= m[ai] * integ
                if g is not None and s is not None:
                    row = s[ai]
                    for p, ds in enumerate(row):
                        g[p] -= ds * integ
                    d_integ_logb = ((1.0 + x) * math.exp(-x) - 1.0) / b
                    g[idx_beta[target][source]] -= m[ai] * d_integ_logb
    return ll


def _jump_event(
    ci: int,
    m: List[float],
    s: Optional[List[List[float]]],
    eta: Sequence[Sequence[float]],
    beta: Sequence[Sequence[float]],
    maps: Dict[str, Any],
) -> None:
    k = len(eta)
    n = k * k
    gamma2 = len(m) == 2 * n
    idx_eta = maps["eta"]
    idx_beta = maps["beta"]
    for target in range(k):
        ai = target * k + ci
        jump = eta[target][ci] * beta[target][ci]
        state_index = n + ai if gamma2 else ai
        m[state_index] += jump
        if s is not None:
            s[state_index][idx_eta[target][ci]] += jump
            s[state_index][idx_beta[target][ci]] += jump


def _stationary_state(
    mu: Sequence[Sequence[float]],
    eta: Sequence[Sequence[float]],
    beta: Sequence[Sequence[float]],
    r0: int,
    spec: ModelSpec,
    pspec: List[Tuple[str, int, int]],
    maps: Dict[str, Any],
    with_grad: bool,
) -> Tuple[List[float], Optional[List[List[float]]], float]:
    k = spec.k
    gamma2 = getattr(spec, "kernel_shape", "exp") == "gamma2"
    h = [row[:] for row in eta]
    rho = spectral_radius(h)
    if rho >= 0.999999:
        raise UnstableModel(f"stationary boundary requires rho(eta)<1, got {rho:.4f}")
    mat = [[(1.0 if i == j else 0.0) - h[i][j] for j in range(k)] for i in range(k)]
    mu0 = [mu[i][r0] for i in range(k)]
    lam = solve_linear(mat, mu0)
    lam = [max(x, 1e-12) for x in lam]
    m = [0.0] * (k * k)
    for target in range(k):
        for source in range(k):
            m[target * k + source] = eta[target][source] * lam[source]
    if gamma2:
        # Both cascade states have the same stationary first moment.
        m = m + m[:]

    if not with_grad:
        return m, None, rho

    pcount = len(pspec)
    base_s = [[0.0] * pcount for _ in range(k * k)]
    s = base_s
    idx_mu, idx_eta = maps["mu"], maps["eta"]

    def fill_from_dlam(dlam: Sequence[float], varied: Optional[Tuple[int, int]], qidx: int) -> None:
        for target in range(k):
            for source in range(k):
                ai = target * k + source
                deriv = eta[target][source] * dlam[source]
                if varied == (target, source):
                    deriv += eta[target][source] * lam[source]
                s[ai][qidx] = deriv

    for cat in range(k):
        qidx = idx_mu[cat][r0]
        rhs = [0.0] * k
        rhs[cat] = mu[cat][r0]  # derivative wrt log mu
        dlam = solve_linear(mat, rhs)
        fill_from_dlam(dlam, None, qidx)

    for t0 in range(k):
        for j0 in range(k):
            qidx = idx_eta[t0][j0]
            rhs = [0.0] * k
            rhs[t0] = eta[t0][j0] * lam[j0]  # H' Lambda wrt log eta
            dlam = solve_linear(mat, rhs)
            fill_from_dlam(dlam, (t0, j0), qidx)
    if gamma2:
        s = [row[:] for row in base_s] + [row[:] for row in base_s]
    return m, s, rho


class UnstableModel(RuntimeError):
    pass


def _missing_derivatives(
    m: Sequence[float],
    s: Optional[Sequence[Sequence[float]]],
    mu_vec: Sequence[float],
    eta: Sequence[Sequence[float]],
    beta: Sequence[Sequence[float]],
    pspec_len: int,
) -> Tuple[List[float], Optional[List[List[float]]]]:
    k = len(eta)
    d = k * k
    fm = [0.0] * d
    # lambda_j = mu_j + sum_l m[j,l]
    lam = [mu_vec[j] + sum(m[j * k + l] for l in range(k)) for j in range(k)]
    jac = [[0.0] * d for _ in range(d)]
    ftheta = [[0.0] * pspec_len for _ in range(d)] if s is not None else None
    for target in range(k):
        for source in range(k):
            a = target * k + source
            b = beta[target][source]
            e = eta[target][source]
            fm[a] = -b * m[a] + e * b * lam[source]
            jac[a][a] = -b
            # lambda_source derivative wrt state (source, l)
            for l in range(k):
                bidx = source * k + l
                jac[a][bidx] += e * b
            if s is not None and ftheta is not None:
                # Explicit parameter derivatives at fixed m.  Gradient mapping
                # is handled by caller through parameter indices; here return
                # dense derivatives keyed by temporary beta/eta variables?  We
                # instead compute directly into global q indices below via
                # special return arrays.
                pass
    if s is None:
        return fm, None

    # S' = J S + f_theta.  f_theta has entries only for the eta/beta q indices,
    # but common-beta mapping is known by caller.  Return J and lambda so the
    # RK4 routine can construct ftheta with maps.
    ds = [[0.0] * pspec_len for _ in range(d)]
    for a in range(d):
        for p in range(pspec_len):
            ds[a][p] = sum(jac[a][b] * s[b][p] for b in range(d))
    return fm, ds


def _relax_gap(
    m: List[float],
    s: Optional[List[List[float]]],
    dt: float,
    mu: Sequence[Sequence[float]],
    eta: Sequence[Sequence[float]],
    beta: Sequence[Sequence[float]],
    maps: Dict[str, Any],
    pspec_len: int,
    bg_r: int = 0,
) -> bool:
    """Approximate an unobserved interval by relaxation to the stationary mean.

    Unlike a zero-state reset, this preserves the decayed contribution of known
    pre-gap events while injecting the first-moment contribution of background
    and unobserved descendant events.  Returns False when no stable stationary
    mean exists and the caller should fall back to plain decay.
    """
    if dt <= 1e-14:
        return True
    k = len(eta)
    n = k * k
    gamma2 = len(m) == 2 * n
    idx_beta = maps["beta"]
    try:
        fake_spec = type("_TinySpec", (), {"k": k, "kernel_shape": "gamma2" if gamma2 else "exp"})()
        m_stat, s_stat, _ = _stationary_state(
            mu, eta, beta, bg_r, fake_spec, list(range(pspec_len)), maps, s is not None
        )
    except UnstableModel:
        return False

    for a in range(n):
        target = a // k
        source = a % k
        b = beta[target][source]
        x = b * dt
        f = math.exp(-x)
        qb = idx_beta[target][source]
        if gamma2:
            ai_aux = n + a
            old_b, old_a = m[a], m[ai_aux]
            stat_b, stat_a = m_stat[a], m_stat[ai_aux]
            g = x * f
            m[a] = stat_b + (old_b - stat_b) * f + g * (old_a - stat_a)
            m[ai_aux] = stat_a + (old_a - stat_a) * f
        else:
            old_b = m[a]
            m[a] = m_stat[a] + (old_b - m_stat[a]) * f
        if s is not None and s_stat is not None:
            row = s[a]
            old_row = row[:]  # S_old is overwritten below.
            if gamma2:
                row_aux = s[n + a]
                old_row_aux = row_aux[:]
                g = x * f
                for p in range(pspec_len):
                    row[p] = f * old_row[p] + (1.0 - f) * s_stat[a][p] + g * old_row_aux[p] - g * s_stat[ai_aux][p]
                    row_aux[p] = f * old_row_aux[p] + (1.0 - f) * s_stat[ai_aux][p]
                delta_b = old_b - stat_b
                delta_a = old_a - stat_a
                row[qb] += -delta_b * x * f + delta_a * x * f * (1.0 - x)
                row_aux[qb] += -delta_a * x * f
            else:
                for p in range(pspec_len):
                    row[p] = f * old_row[p] + (1.0 - f) * s_stat[a][p]
                # Explicit derivative of the relaxation factor f=exp(-beta*L)
                # with respect to log beta.
                row[qb] += (old_b - m_stat[a]) * (-dt * b * f)
    return True


def _rk4_missing(
    m: List[float],
    s: Optional[List[List[float]]],
    dt: float,
    mu_vec: Sequence[float],
    eta: Sequence[Sequence[float]],
    beta: Sequence[Sequence[float]],
    maps: Dict[str, Any],
    pspec_len: int,
    bg_r: int = 0,
) -> None:
    """Propagate first-moment state through an unobserved interval."""
    if dt <= 1e-14:
        return
    k = len(eta)
    max_b = max(max(row) for row in beta)
    steps = max(1, int(math.ceil(dt * max_b / 0.35)))
    steps = min(steps, 400)
    h = dt / steps
    idx_eta = maps["eta"]
    idx_beta = maps["beta"]

    def deriv(cur_m: List[float], cur_s: Optional[List[List[float]]]):
        lam = [mu_vec[j] + sum(cur_m[j * k + l] for l in range(k)) for j in range(k)]
        fm = [0.0] * (k * k)
        for target in range(k):
            for source in range(k):
                a = target * k + source
                b = beta[target][source]
                fm[a] = -b * cur_m[a] + eta[target][source] * b * lam[source]
        if cur_s is None:
            return fm, None
        ds = [[0.0] * pspec_len for _ in range(k * k)]
        for target in range(k):
            for source in range(k):
                a = target * k + source
                b = beta[target][source]
                e = eta[target][source]
                for p in range(pspec_len):
                    val = -b * cur_s[a][p]
                    for l in range(k):
                        bidx = source * k + l
                        val += e * b * cur_s[bidx][p]
                    ds[a][p] = val
                # explicit derivatives wrt log eta and log beta
                qe = idx_eta[target][source]
                qb = idx_beta[target][source]
                f_eta = e * b * lam[source]
                f_beta = b * (-cur_m[a] + e * lam[source])
                ds[a][qe] += f_eta
                ds[a][qb] += f_beta
                # Explicit background derivative in an unobserved interval.
                qmu = maps["mu"][source][bg_r]
                ds[a][qmu] += e * b * mu_vec[source]
        return fm, ds

    for _ in range(steps):
        if s is None:
            k1, _ = deriv(m, None)
            m2 = [m[i] + 0.5 * h * k1[i] for i in range(len(m))]
            k2, _ = deriv(m2, None)
            m3 = [m[i] + 0.5 * h * k2[i] for i in range(len(m))]
            k3, _ = deriv(m3, None)
            m4 = [m[i] + h * k3[i] for i in range(len(m))]
            k4, _ = deriv(m4, None)
            for i in range(len(m)):
                m[i] += h * (k1[i] + 2 * k2[i] + 2 * k3[i] + k4[i]) / 6.0
        else:
            k1m, k1s = deriv(m, s)
            m2 = [m[i] + 0.5 * h * k1m[i] for i in range(len(m))]
            s2 = [[s[a][p] + 0.5 * h * k1s[a][p] for p in range(pspec_len)] for a in range(k * k)]
            k2m, k2s = deriv(m2, s2)
            m3 = [m[i] + 0.5 * h * k2m[i] for i in range(len(m))]
            s3 = [[s[a][p] + 0.5 * h * k2s[a][p] for p in range(pspec_len)] for a in range(k * k)]
            k3m, k3s = deriv(m3, s3)
            m4 = [m[i] + h * k3m[i] for i in range(len(m))]
            s4 = [[s[a][p] + h * k3s[a][p] for p in range(pspec_len)] for a in range(k * k)]
            k4m, k4s = deriv(m4, s4)
            for i in range(k * k):
                m[i] += h * (k1m[i] + 2 * k2m[i] + 2 * k3m[i] + k4m[i]) / 6.0
                for p in range(pspec_len):
                    s[i][p] += h * (k1s[i][p] + 2 * k2s[i][p] + 2 * k3s[i][p] + k4s[i][p]) / 6.0


def likelihood(
    params: Dict[str, List[List[float]]],
    scope: Dict[str, Any],
    model: ModelSpec,
    pspec: List[Tuple[str, int, int]],
    maps: Dict[str, Any],
    *,
    boundary: str = "stationary",
    gap_correction: bool = True,
    want_grad: bool = False,
    initial_m: Optional[Sequence[float]] = None,
    initial_s: Optional[List[List[float]]] = None,
    return_trace: bool = False,
    max_rho: Optional[float] = None,
) -> Dict[str, Any]:
    mu, eta, beta = params["mu"], params["eta"], params["beta"]
    k = model.k
    rho = spectral_radius(eta)
    if max_rho is not None and rho >= max_rho:
        raise UnstableModel(f"rho={rho:.4f} >= {max_rho}")

    g = [0.0] * len(pspec) if want_grad else None
    windows = scope["windows"]
    if not windows:
        raise ValueError("Scope has no observation windows")

    state_size = model.state_size
    m: List[float] = [0.0] * state_size
    s: Optional[List[List[float]]] = [[0.0] * len(pspec) for _ in range(state_size)] if want_grad else None
    ll = 0.0
    event_rows: List[Dict[str, Any]] = []
    final_state: List[float] = []

    # Optional externally supplied state (holdout initialized from training).
    if initial_m is not None:
        m = list(initial_m)
        if want_grad and initial_s is not None:
            s = [row[:] for row in initial_s]
        elif want_grad:
            s = [[0.0] * len(pspec) for _ in range(len(m))]
    else:
        if boundary == "stationary":
            r0 = model.bg_index(windows[0][0])
            m, ss, _ = _stationary_state(mu, eta, beta, r0, model, pspec, maps, want_grad)
            if want_grad:
                s = ss
        elif boundary == "warmup" and scope.get("history_start") is not None:
            hs = scope["history_start"]
            warm = [e for e in scope.get("parent_data", scope).get("events", []) if hs <= e["t"] < windows[0][0]]
            warm.sort(key=lambda e: e["t"])
            cursor = hs
            for e in warm:
                _decay_state(m, s, e["t"] - cursor, beta, maps["beta"])
                _jump_event(e["ci"], m, s, eta, beta, maps)
                cursor = e["t"]
            _decay_state(m, s, windows[0][0] - cursor, beta, maps["beta"])
        # boundary == observed/zero leaves zero state.

    ev_idx = 0
    events = scope["events"]
    for wi, (a, b) in enumerate(windows):
        if wi > 0:
            pa, pb = windows[wi - 1]
            gap_start, gap_end = pb, a
            gap = gap_end - gap_start
            if gap > 1e-12:
                if gap_correction:
                    # Split missing interval at background complexity cuts.
                    bounds = [gap_start] + [c for c in model.cuts if gap_start < c < gap_end] + [gap_end]
                    cursor = gap_start
                    for x, y in zip(bounds[:-1], bounds[1:]):
                        rr = model.bg_index((x + y) / 2)
                        ok = _relax_gap(m, s if want_grad else None, y - x, mu, eta, beta, maps, len(pspec), rr)
                        if not ok:
                            _decay_state(m, s, y - x, beta, maps["beta"])
                else:
                    _decay_state(m, s, gap, beta, maps["beta"])

        cursor = a
        # Events in this window.  Endpoint b is accepted only for final merged window semantics.
        these_events = []
        while ev_idx < len(events) and events[ev_idx]["t"] < a:
            ev_idx += 1
        j = ev_idx
        while j < len(events) and a <= events[j]["t"] <= b:
            these_events.append(events[j])
            j += 1

        pos = 0
        while pos < len(these_events):
            t = these_events[pos]["t"]
            group = []
            while pos < len(these_events) and abs(these_events[pos]["t"] - t) <= 1e-10:
                group.append(these_events[pos])
                pos += 1
            # Integrate/decay in pieces split by background cuts.
            sub_bounds = [cursor] + [c for c in model.cuts if cursor < c < t] + [t]
            for x, y in zip(sub_bounds[:-1], sub_bounds[1:]):
                if y > x:
                    rr = model.bg_index((x + y) / 2.0)
                    ll = _interval_compensator(m, s, y - x, mu, rr, eta, beta, maps, ll, g)
                    _decay_state(m, s, y - x, beta, maps["beta"])
            cursor = t

            # Tied/rounded timestamps form one simultaneous batch.  Evaluate
            # every member before applying any jump so arbitrary CSV row order
            # cannot create zero-lag parent links inside the batch.
            r_now = model.bg_index(t)
            pre_event_s = [row[:] for row in s] if (g is not None and s is not None) else None
            for e in group:
                ci = e["ci"]
                bg = mu[ci][r_now]
                trig = [m[ci * k + source] for source in range(k)]
                lam = bg + sum(trig)
                if lam <= 0 or not math.isfinite(lam):
                    raise FloatingPointError("non-positive intensity")
                ll += math.log(lam)
                if g is not None and s is not None and pre_event_s is not None:
                    g[maps["mu"][ci][r_now]] += bg / lam
                    for p in range(len(pspec)):
                        deriv_lam = sum(pre_event_s[ci * k + source][p] for source in range(k))
                        g[p] += deriv_lam / lam
                if return_trace:
                    event_rows.append(
                        {
                            "t": t,
                            "ci": ci,
                            "category": scope["categories"][ci],
                            "lambda": lam,
                            "background": bg,
                            "trigger": sum(trig),
                            "source_components": trig,
                            "background_probability": bg / lam,
                            "trigger_probability": sum(trig) / lam,
                            "log_intensity": math.log(lam),
                            "tied_batch_size": len(group),
                        }
                    )
            for e in group:
                _jump_event(e["ci"], m, s, eta, beta, maps)

        # Advance event index past processed events.
        ev_idx = j
        # Window-tail compensator, split by background cuts.
        sub_bounds = [cursor] + [c for c in model.cuts if cursor < c < b] + [b]
        for x, y in zip(sub_bounds[:-1], sub_bounds[1:]):
            if y > x:
                rr = model.bg_index((x + y) / 2.0)
                ll = _interval_compensator(m, s, y - x, mu, rr, eta, beta, maps, ll, g)
                _decay_state(m, s, y - x, beta, maps["beta"])
        cursor = b
        final_state = m[:]

    result = {
        "loglik": ll,
        "gradient": g,
        "rho": rho,
        "event_rows": event_rows if return_trace else None,
        "final_state": final_state,
        "final_state_time": windows[-1][1] if windows else None,
    }
    return result



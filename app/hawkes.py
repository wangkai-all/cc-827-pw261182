def is_finite_number(x: Any) -> bool:
    return isinstance(x, (int, float)) and not isinstance(x, bool) and math.isfinite(float(x))


def mat_vec(a: Sequence[Sequence[float]], x: Sequence[float]) -> List[float]:
    return [sum(a[i][j] * x[j] for j in range(len(x))) for i in range(len(a))]


def solve_linear(a: Sequence[Sequence[float]], b: Sequence[float]) -> List[float]:
    """Gaussian elimination with partial pivoting; matrices are tiny (K <= ~8)."""
    n = len(b)
    m = [list(map(float, a[i])) + [float(b[i])] for i in range(n)]
    for col in range(n):
        pivot = max(range(col, n), key=lambda r: abs(m[r][col]))
        if abs(m[pivot][col]) < 1e-14:
            # Add a tiny diagonal instead of failing on a numerically singular M.
            m[col][col] += 1e-10
            pivot = col
        if pivot != col:
            m[col], m[pivot] = m[pivot], m[col]
        pv = m[col][col]
        for r in range(col + 1, n):
            factor = m[r][col] / pv
            if factor == 0.0:
                continue
            m[r][col] = 0.0
            for c in range(col + 1, n + 1):
                m[r][c] -= factor * m[col][c]
    x = [0.0] * n
    for i in range(n - 1, -1, -1):
        x[i] = (m[i][n] - sum(m[i][j] * x[j] for j in range(i + 1, n))) / m[i][i]
    return x


def spectral_radius(h: Sequence[Sequence[float]], iters: int = 80) -> float:
    """Power iteration for the nonnegative branching matrix."""
    k = len(h)
    if k == 0:
        return 0.0
    v = [1.0 / math.sqrt(k)] * k
    rho = 0.0
    for _ in range(iters):
        w = mat_vec(h, v)
        norm = math.sqrt(sum(x * x for x in w))
        if norm < 1e-18:
            return 0.0
        v = [x / norm for x in w]
        rho = norm
    # Rayleigh quotient with a left vector is more accurate for non-symmetric H.
    hv = mat_vec(h, v)
    denom = sum(v[i] * v[i] for i in range(k))
    return sum(v[i] * hv[i] for i in range(k)) / denom if denom else rho


def spectral_pair(h: Sequence[Sequence[float]]) -> Tuple[float, List[float], List[float]]:
    k = len(h)
    v = [1.0 / math.sqrt(k)] * k
    for _ in range(120):
        w = mat_vec(h, v)
        nrm = math.sqrt(sum(x * x for x in w))
        if nrm < 1e-18:
            return 0.0, v, v
        v = [x / nrm for x in w]
    rho = sum(v[i] * sum(h[i][j] * v[j] for j in range(k)) for i in range(k))
    # Left eigenvector via power iteration on H^T.
    w = [1.0 / math.sqrt(k)] * k
    ht = [[h[j][i] for j in range(k)] for i in range(k)]
    for _ in range(120):
        nw = mat_vec(ht, w)
        nrm = math.sqrt(sum(x * x for x in nw))
        if nrm < 1e-18:
            break
        w = [x / nrm for x in nw]
    return rho, w, v


def clamp(x: float, lo: float, hi: float) -> float:
    return max(lo, min(hi, x))


def median(xs: Sequence[float]) -> float:
    if not xs:
        return 0.0
    ys = sorted(xs)
    n = len(ys)
    if n % 2:
        return ys[n // 2]
    return 0.5 * (ys[n // 2 - 1] + ys[n // 2])


def quantile_sorted(xs: Sequence[float], p: float) -> float:
    if not xs:
        return 0.0
    if len(xs) == 1:
        return xs[0]
    pos = (len(xs) - 1) * p
    lo = int(math.floor(pos))
    hi = int(math.ceil(pos))
    if lo == hi:
        return xs[lo]
    return xs[lo] * (hi - pos) + xs[hi] * (pos - lo)



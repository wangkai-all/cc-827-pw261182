def simulate_hawkes(
    categories: List[str],
    mu: Sequence[Sequence[float]],
    eta: Sequence[Sequence[float]],
    beta: Sequence[Sequence[float]],
    end: float,
    *,
    start: float = 0.0,
    cuts: Optional[List[float]] = None,
    seed: int = 1,
) -> List[Dict[str, Any]]:
    """Exact cluster simulation for piecewise-constant immigrant rates."""
    rng = random.Random(seed)
    k = len(categories)
    cuts = sorted(cuts or [])

    def r_index(t: float) -> int:
        return sum(t >= c for c in cuts)

    events: List[Dict[str, Any]] = []

    def add_descendants(parent_t: float, parent_cat: int) -> None:
        stack = [(parent_t, parent_cat)]
        while stack:
            pt, pc = stack.pop()
            for target in range(k):
                branching = eta[target][pc]
                nchild = rng.poisson(branching) if hasattr(rng, "poisson") else _poisson(rng, branching)
                b = beta[target][pc]
                for _ in range(nchild):
                    # Inverse CDF of eta*beta exp(-beta u) normalized by eta.
                    u = rng.random()
                    lag = -math.log(max(1 - u, 1e-12)) / b
                    ct = pt + lag
                    if ct <= end:
                        child = {"t": ct, "ci": target, "category": categories[target]}
                        events.append(child)
                        stack.append((ct, target))

    # Immigrants per category and background segment.
    bounds = [start] + cuts + [end]
    for x, y in zip(bounds[:-1], bounds[1:]):
        if y <= x:
            continue
        rr = r_index((x + y) / 2)
        for ci in range(k):
            rate = mu[ci][min(rr, len(mu[ci]) - 1)]
            n = _poisson(rng, rate * (y - x))
            for _ in range(n):
                t = x + rng.random() * (y - x)
                ev = {"t": t, "ci": ci, "category": categories[ci]}
                events.append(ev)
                add_descendants(t, ci)
    events.sort(key=lambda e: (e["t"], e["ci"]))
    for i, e in enumerate(events):
        e["id"] = i
    return events


def _poisson(rng: random.Random, lam: float) -> int:
    if lam <= 0:
        return 0
    if lam < 30:
        l = math.exp(-lam)
        k = 0
        p = 1.0
        while True:
            k += 1
            p *= rng.random()
            if p <= l:
                return k - 1
    # Normal approximation is only used for large synthetic counts.
    return max(0, int(rng.gauss(lam, math.sqrt(lam)) + 0.5))


def round_events(events: Sequence[Dict[str, Any]], resolution: float) -> List[Dict[str, Any]]:
    out = []
    for e in events:
        ne = dict(e)
        ne["t"] = round(round(e["t"] / resolution) * resolution, 10)
        out.append(ne)
    out.sort(key=lambda e: (e["t"], e["ci"]))
    return out


def synthetic_dataset(scenario: str, seed: int = 11, resolution: Optional[float] = None) -> Dict[str, Any]:
    categories = ["A", "B"]
    if scenario == "background_only":
        mu = [[0.55], [0.35]]
        eta = [[0.0, 0.0], [0.0, 0.0]]
        beta = [[1.0, 1.0], [1.0, 1.0]]
        windows = [(0.0, 120.0)]
        true = {"mu": mu, "eta": eta, "beta": beta}
        events = simulate_hawkes(categories, mu, eta, beta, 120, seed=seed)
        res = resolution or 0.25
    elif scenario == "self_excitation":
        mu = [[0.34], [0.22]]
        eta = [[0.52, 0.10], [0.08, 0.46]]
        beta = [[1.35, 0.9], [0.8, 1.15]]
        windows = [(0.0, 120.0)]
        true = {"mu": mu, "eta": eta, "beta": beta}
        events = simulate_hawkes(categories, mu, eta, beta, 120, seed=seed)
        res = resolution or 0.1
    elif scenario == "cross_trigger":
        categories = ["web", "support"]
        mu = [[0.42], [0.25]]
        eta = [[0.18, 0.06], [0.48, 0.16]]  # web events strongly trigger support
        beta = [[0.9, 0.7], [1.6, 0.8]]
        windows = [(0.0, 120.0)]
        true = {"mu": mu, "eta": eta, "beta": beta}
        events = simulate_hawkes(categories, mu, eta, beta, 120, seed=seed)
        res = resolution or 0.1
    elif scenario == "background_shift":
        cuts = [60.0]
        mu = [[0.25, 1.25], [0.18, 0.72]]
        eta = [[0.03, 0.0], [0.0, 0.02]]
        beta = [[1.2, 1.0], [1.0, 1.4]]
        windows = [(0.0, 120.0)]
        true = {"mu": mu, "eta": eta, "beta": beta, "cuts": cuts}
        events = simulate_hawkes(categories, mu, eta, beta, 120, cuts=cuts, seed=seed)
        res = resolution or 0.2
    elif scenario == "observation_gaps":
        mu = [[0.42], [0.26]]
        eta = [[0.42, 0.08], [0.12, 0.38]]
        beta = [[1.2, 0.9], [1.0, 1.3]]
        # Active mornings/evenings over five days; long stopped intervals.
        windows = []
        for d in range(5):
            windows.append((24 * d + 2, 24 * d + 10))
            windows.append((24 * d + 14, 24 * d + 22))

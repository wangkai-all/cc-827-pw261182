"""Core multivariate Hawkes fitting, diagnostics and simulation.

The implementation intentionally depends only on the Python standard library.
It supports a sharp exponential kernel,

    phi_{k<-j}(u) = eta[k, j] * beta[k, j] * exp(-beta[k, j] * u),

and a delayed normalized Gamma(2) kernel,

    phi_{k<-j}(u) = eta[k, j] * beta[k, j]^2 * u * exp(-beta[k, j] * u).

In both cases eta is the expected number of direct category-k children
generated by one category-j event.  The stability condition is
spectral_radius(eta) < 1.

The likelihood is a windowed conditional likelihood.  Active windows contribute
event log-terms and compensator integrals; gaps contribute no integral.  State
from observed events decays through gaps and can optionally be propagated
through a first-moment correction for events that were unobserved during a
stoppage.
"""

from __future__ import annotations

import math
import random
from dataclasses import dataclass
from datetime import datetime
from typing import Any, Callable, Dict, Iterable, List, Optional, Sequence, Tuple


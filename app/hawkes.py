def fit_model(
    scope: Dict[str, Any],
    categories: List[str],
    *,
    bg_bins: int = 1,
    cuts: Optional[List[float]] = None,
    beta_mode: str = "pair",
    kernel_shape: str = "exp",
    boundary: str = "stationary",
    gap_correction: bool = True,
    enforce_stable: bool = True,
    max_iter: int = 260,
    random_restarts: int = 1,
    seed: int = 7,
) -> Dict[str, Any]:
    if cuts is None:
        cuts = equal_exposure_cuts(scope["windows"], bg_bins) if bg_bins > 1 else []
    model = ModelSpec(categories=categories, cuts=sorted(cuts), beta_mode=beta_mode, kernel_shape=kernel_shape)
    pspec, maps = model.build_index()
    init = initial_parameters(scope, model)
    q0 = pack_params(init, model, pspec, maps)
    beta0 = init["beta0"]

    pcount = len(pspec)
    lo = [-13.0] * pcount
    hi = [8.0] * pcount
    for p, (kind, i, j) in enumerate(pspec):
        if kind == "beta":
            # Keep timescales inside the range that this record can identify.
            # Extremely fast kernels are destroyed by rounded timestamps and
            # extremely slow kernels are indistinguishable from background.
            span = max(scope.get("calendar_span", 1.0), 1e-6)
            res = scope.get("resolution")
            bmin = max(beta0 / 60.0, 2.5 / span)
            bmax = beta0 * 45.0
            if is_finite_number(res) and res and res > 0:
                bmax = min(bmax, 8.0 / float(res))
            bmin = min(bmin, beta0 / 3.0)
            bmax = max(bmax, beta0 * 3.0)
            lo[p] = math.log(clamp(bmin, 1e-6, 1e6))
            hi[p] = math.log(clamp(bmax, 1e-6, 1e6))
        if kind == "eta":
            lo[p] = math.log(1e-4)
            hi[p] = math.log(2.5)
        if kind == "mu":
            lo[p] = math.log(1e-8)
            hi[p] = math.log(1e4)

    def project(q: List[float]) -> List[float]:
        return [clamp(q[p], lo[p], hi[p]) for p in range(pcount)]

    def eval_q(q: List[float], grad: bool = True):
        params = unpack_q(q, model, pspec)
        try:
            out = likelihood(
                params,
                scope,
                model,
                pspec,
                maps,
                boundary=boundary,
                gap_correction=gap_correction,
                want_grad=grad,
                max_rho=0.995 if enforce_stable else None,
            )
        except (UnstableModel, FloatingPointError, OverflowError, ValueError):
            return None
        # Weak smooth regularizer keeps extreme log-parameters in a useful basin.
        reg = 1e-5 * sum(x * x for x in q)
        out["objective"] = out["loglik"] - reg
        if grad and out["gradient"] is not None:
            for p in range(pcount):
                out["gradient"][p] -= 2e-5 * q[p]
        return out

    starts = [q0]
    rng = random.Random(seed)
    for r in range(max(0, random_restarts - 1)):
        q = q0[:]
        for p, (kind, i, j) in enumerate(pspec):
            if kind == "beta":
                q[p] += math.log(rng.choice([0.25, 0.5, 2.0, 4.0])) + rng.uniform(-0.2, 0.2)
            elif kind == "eta":
                q[p] += rng.uniform(-0.8, 0.4)
            else:
                q[p] += rng.uniform(-0.25, 0.25)
        starts.append(project(q))

    best: Optional[Dict[str, Any]] = None
    best_q: Optional[List[float]] = None
    for restart_id, start in enumerate(starts):
        q = project(start)
        m_adam = [0.0] * pcount
        v_adam = [0.0] * pcount
        best_local_q = q[:]
        best_local_obj = -math.inf
        bad = 0
        lr = 0.045 if restart_id == 0 else 0.04
        for it in range(1, max_iter + 1):
            out = eval_q(q, True)
            if out is None:
                # Should be rare after projection/stability; shrink eta-like q.
                for p, (kind, _, _) in enumerate(pspec):
                    if kind == "eta":
                        q[p] -= 0.25
                q = project(q)
                continue
            obj = out["objective"]
            g = out["gradient"] or [0.0] * pcount
            gnorm = math.sqrt(sum(x * x for x in g))
            if gnorm > 80:
                g = [x * 80 / gnorm for x in g]
            if obj > best_local_obj + 1e-7:
                best_local_obj = obj
                best_local_q = q[:]
                bad = 0
            else:
                bad += 1
            if bad >= 45:
                break
            a1, a2, eps = 0.9, 0.999, 1e-8
            for p in range(pcount):
                m_adam[p] = a1 * m_adam[p] + (1 - a1) * g[p]
                v_adam[p] = a2 * v_adam[p] + (1 - a2) * g[p] * g[p]
                mh = m_adam[p] / (1 - a1 ** it)
                vh = v_adam[p] / (1 - a2 ** it)
                step = lr * mh / (math.sqrt(vh) + eps)
                q[p] = clamp(q[p] + step, lo[p], hi[p])

        final = eval_q(best_local_q, False) or eval_q(q, False)
        if final is None:
            continue
        if best is None or final["loglik"] > best["loglik"]:
            best = final
            best_q = best_local_q[:]

    if best is None or best_q is None:
        raise RuntimeError("Fit failed for all initializations")

    params = unpack_q(best_q, model, pspec)
    rho = best["rho"]
    n_events = len(scope["events"])
    # Parameter count: all fitted log parameters.  In common-beta mode this is
    # already reduced by the parameter specification.
    k_params = len(pspec) + len(model.cuts)
    aic = 2 * k_params - 2 * best["loglik"]
    bic = k_params * math.log(max(n_events, 2)) - 2 * best["loglik"]
    result = {
        "params": params,
        "rho": rho,
        "stable": rho < 1.0,
        "stationary_forecast_allowed": rho < 0.999,
        "loglik": best["loglik"],
        "aic": aic,
        "bic": bic,
        "n_params": k_params,
        "n_events": n_events,
        "boundary": boundary,
        "gap_correction": gap_correction,
        "beta_mode": beta_mode,
        "kernel_shape": kernel_shape,
        "model_family": "hawkes_gamma2" if kernel_shape == "gamma2" else "hawkes_exp",
        "bg_bins": len(model.cuts) + 1,
        "cuts": model.cuts,
        "categories": categories,
        "final_state": best.get("final_state"),
        "final_state_time": best.get("final_state_time", scope["windows"][-1][1] if scope.get("windows") else None),
        "spec": model,
        "pspec": pspec,
        "maps": maps,
        "q": best_q,
    }
    return result


def fit_candidate_set(
    train_scope: Dict[str, Any],
    categories: List[str],
    options: Optional[Dict[str, Any]] = None,
) -> Dict[str, Any]:
    """Fit training-only candidates and select by AIC/BIC.

    The holdout segment is deliberately not touched here.
    """
    options = options or {}
    boundary = options.get("boundary", "stationary")
    gap_correction = bool(options.get("gap_correction", True))
    enforce_stable = bool(options.get("enforce_stable", True))
    complexity = options.get("background_complexity", "auto")
    kernel_complexity = options.get("kernel_complexity", "auto")
    kernel_shape_option = options.get("kernel_shape", "auto")
    max_iter = int(options.get("max_iter", 240))

    bg_choices = [1, 2, 3] if complexity == "auto" else [int(complexity)]
    beta_choices = ["common", "pair"] if kernel_complexity == "auto" else [str(kernel_complexity)]
    if kernel_shape_option == "auto":
        shape_choices = ["exp", "gamma2"]
    else:
        shape_choices = [str(kernel_shape_option)]
    candidates = []
    errors = []
    for bins in bg_choices:
        for beta_mode in beta_choices:
            for kernel_shape in shape_choices:
                try:
                    fit = fit_model(
                        train_scope,
                        categories,
                        bg_bins=bins,
                        beta_mode=beta_mode,
                        kernel_shape=kernel_shape,
                        boundary=boundary,
                        gap_correction=gap_correction,
                        enforce_stable=enforce_stable,
                        max_iter=max_iter,
                        random_restarts=2 if beta_mode == "pair" else 1,
                    )
                    candidates.append(fit)
                except Exception as e:  # keep other candidates usable
                    errors.append(f"bg={bins},beta={beta_mode},shape={kernel_shape}: {e}")

    # Poisson baseline candidates (eta=0).  These are important negative controls.
    for bins in bg_choices:
        try:
            fit = fit_poisson(train_scope, categories, bg_bins=bins, max_iter=max_iter)
            candidates.append(fit)
        except Exception as e:
            errors.append(f"poisson bg={bins}: {e}")

    if not candidates:
        raise RuntimeError("No candidate model could be fitted: " + "; ".join(errors))
    selected = min(candidates, key=lambda f: f["aic"])
    return {"selected": selected, "candidates": candidates, "errors": errors}


def fit_poisson(scope: Dict[str, Any], categories: List[str], bg_bins: int = 1, max_iter: int = 100) -> Dict[str, Any]:
    """Fit a piecewise-constant independent-category Poisson baseline exactly."""
    cuts = equal_exposure_cuts(scope["windows"], bg_bins) if bg_bins > 1 else []
    model = ModelSpec(categories, sorted(cuts), "common")
    k, r = model.k, model.r
    counts = [[0] * r for _ in range(k)]
    exposure = [0.0] * r
    for a, b in scope["windows"]:
        bounds = [a] + [c for c in model.cuts if a < c < b] + [b]
        for x, y in zip(bounds[:-1], bounds[1:]):
            rr = model.bg_index((x + y) / 2)
            exposure[rr] += y - x
    for e in scope["events"]:
        counts[e["ci"]][model.bg_index(e["t"])] += 1
    # Keep unseen category/bin rates on the same positive numerical floor used
    # by Hawkes MLE.  A holdout event in a cell with zero training counts then
    # yields a finite, strongly negative likelihood instead of crashing on log(0).
    mu = [[max(counts[ci][rr] / exposure[rr], 1e-8) if exposure[rr] > 0 else 1e-6 for rr in range(r)] for ci in range(k)]
    ll = 0.0
    for ci in range(k):
        for rr in range(r):
            lam = mu[ci][rr]
            ll += counts[ci][rr] * math.log(max(lam, 1e-12)) - lam * exposure[rr]
    eta = [[0.0] * k for _ in range(k)]
    beta = [[1.0] * k for _ in range(k)]
    pspec, maps = model.build_index()
    npar = k * r + len(model.cuts)
    return {
        "params": {"mu": mu, "eta": eta, "beta": beta},
        "rho": 0.0,
        "stable": True,
        "stationary_forecast_allowed": True,
        "loglik": ll,
        "aic": 2 * npar - 2 * ll,
        "bic": npar * math.log(max(len(scope["events"]), 2)) - 2 * ll,
        "n_params": npar,
        "n_events": len(scope["events"]),
        "boundary": "poisson",
        "gap_correction": False,
        "beta_mode": "none",
        "model_family": "poisson",
        "bg_bins": r,
        "cuts": model.cuts,
        "categories": categories,
        "final_state": [0.0] * k * k,
        "final_state_time": scope["windows"][-1][1] if scope.get("windows") else None,
        "spec": model,
        "pspec": pspec,
        "maps": maps,
        "q": [],
    }



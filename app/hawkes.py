def parameter_recovery_score(
    truth: Dict[str, Any],
    fit: Dict[str, Any],
    all_categories: Optional[Sequence[str]] = None,
) -> Dict[str, Any]:
    est = fit["params"]
    true_eta_full = truth["eta"]
    true_mu_full = truth["mu"]
    est_eta = est["eta"]
    fit_categories = fit.get("categories") or []

    # The UI may fit a selected subset.  Map those labels back to the synthetic
    # truth order instead of indexing the full matrix with subset dimensions.
    if len(true_eta_full) != len(est_eta) and fit_categories:
        truth_categories = truth.get("categories") or list(all_categories or [])
        if len(truth_categories) == len(true_eta_full):
            positions = [truth_categories.index(c) for c in fit_categories]
        elif all_categories and len(all_categories) == len(true_eta_full):
            positions = [list(all_categories).index(c) for c in fit_categories]
        else:
            # Fall back to the prefix only when labels are unavailable; this is
            # preferable to an IndexError and keeps scalar recovery available.
            positions = list(range(min(len(est_eta), len(true_eta_full))))
        true_eta = [[true_eta_full[i][j] for j in positions] for i in positions]
        true_mu = [true_mu_full[i] for i in positions]
        true_beta_full = truth.get("beta")
        true_beta = (
            [[true_beta_full[i][j] for j in positions] for i in positions]
            if true_beta_full is not None
            else None
        )
    else:
        true_eta = true_eta_full
        true_mu = true_mu_full
        true_beta = truth.get("beta")

    k = len(true_eta)
    eta_abs = []
    eta_rel = []
    for i in range(k):
        for j in range(k):
            eta_abs.append(abs(true_eta[i][j] - est_eta[i][j]))
            if true_eta[i][j] > 0.05:
                eta_rel.append(abs(true_eta[i][j] - est_eta[i][j]) / true_eta[i][j])

    # Compare average background over time when piecewise truth.
    mu_abs = []
    for i in range(k):
        tm = sum(true_mu[i]) / len(true_mu[i])
        em = sum(est["mu"][i]) / len(est["mu"][i])
        mu_abs.append(abs(tm - em) / max(tm, 1e-6))
    beta_abs = []
    if true_beta is not None:
        for i in range(k):
            for j in range(k):
                beta_abs.append(abs(math.log(max(est["beta"][i][j], 1e-6)) - math.log(true_beta[i][j])))
    true_rho = spectral_radius(true_eta)
    return {
        "eta_mae": sum(eta_abs) / len(eta_abs),
        "eta_relative_mae_links": sum(eta_rel) / len(eta_rel) if eta_rel else None,
        "background_relative_mae": sum(mu_abs) / len(mu_abs),
        "beta_log_mae": sum(beta_abs) / len(beta_abs) if beta_abs else None,
        "true_rho": true_rho,
        "estimated_rho": fit["rho"],
        "rho_error": abs(true_rho - fit["rho"]),
        "false_trigger_mass": sum(x for row, trow in zip(est_eta, true_eta) for x, t in zip(row, trow) if t <= 0.05),
    }



def intensity_series(fit: Dict[str, Any], scope: Dict[str, Any], points_per_window: int = 160) -> Dict[str, Any]:
    params = fit["params"]
    model: ModelSpec = fit["spec"]
    maps = fit["maps"]
    pspec = fit["pspec"]
    k = model.k
    # Build a uniform-ish grid across active windows, with gap segments shown too.
    grid_times: List[float] = []
    active_flags: List[bool] = []
    for a, b in scope["windows"]:
        n = max(20, int(points_per_window * (b - a) / max(scope["active_duration"] / len(scope["windows"]), 1e-9)))
        for i in range(n + 1):
            grid_times.append(a + (b - a) * i / n)
            active_flags.append(True)
    # De-duplicate.
    pairs = sorted(set(zip(grid_times, active_flags)))
    ts = [p[0] for p in pairs]

    out = likelihood(
        params,
        scope,
        model,
        pspec,
        maps,
        boundary=fit.get("boundary", "stationary"),
        gap_correction=fit.get("gap_correction", True),
        want_grad=False,
        return_trace=True,
    )
    # Event rows already contain intensities at events; for grid we need a
    # separate deterministic state traversal.
    components = [[] for _ in range(k)]
    totals = []
    bg_series = [[] for _ in range(k)]
    m = [0.0] * model.state_size
    mu, eta, beta = params["mu"], params["eta"], params["beta"]
    boundary = fit.get("boundary", "stationary")
    if boundary == "stationary" and fit.get("rho", 1) < 0.999:
        m, _, _ = _stationary_state(mu, eta, beta, model.bg_index(scope["windows"][0][0]), model, pspec, maps, False)
    cursor = scope["windows"][0][0]
    # Event pointer.
    events = scope["events"]
    ep = 0
    win_idx = 0
    for t in ts:
        # Advance windows/gaps/events until t.  For chart smoothness we process
        # event jumps and intervals in chronological order.
        while win_idx < len(scope["windows"]) and t > scope["windows"][win_idx][1]:
            # advance to window end then gap
            a, b = scope["windows"][win_idx]
            if cursor < b:
                _decay_state(m, None, b - cursor, beta, maps["beta"])
                cursor = b
            if win_idx + 1 < len(scope["windows"]):
                na = scope["windows"][win_idx + 1][0]
                if na > cursor and t >= na:
                    if fit.get("gap_correction", True):
                        rr = model.bg_index((cursor + na) / 2)
                        _relax_gap(m, None, na - cursor, mu, eta, beta, maps, len(pspec), rr)
                    else:
                        _decay_state(m, None, na - cursor, beta, maps["beta"])
                    cursor = na
            win_idx += 1
        # Process events up to t.
        while ep < len(events) and events[ep]["t"] <= t:
            e = events[ep]
            if e["t"] >= cursor:
                _decay_state(m, None, e["t"] - cursor, beta, maps["beta"])
                cursor = e["t"]
            _jump_event(e["ci"], m, None, eta, beta, maps)
            ep += 1
        if t > cursor:
            _decay_state(m, None, t - cursor, beta, maps["beta"])
            cursor = t
        r = model.bg_index(t)
        total = 0.0
        for ci in range(k):
            bg = mu[ci][r]
            trig = sum(m[ci * k + j] for j in range(k))
            bg_series[ci].append(bg)
            components[ci].append(trig)
            total += bg + trig
        totals.append(total)
    return {
        "t": ts,
        "total": totals,
        "background": bg_series,
        "triggered": components,
        "categories": scope["categories"],
        "windows": scope["windows"],
    }


def event_contributions(fit: Dict[str, Any], scope: Dict[str, Any], event_index: int, top_n: int = 12) -> Dict[str, Any]:
    """Exact contribution of every prior observed event to one event's λ."""
    params = fit["params"]
    target_event = scope["events"][event_index]
    tc, tt = target_event["ci"], target_event["t"]
    mu, eta, beta = params["mu"], params["eta"], params["beta"]
    spec: ModelSpec = fit["spec"]
    r = spec.bg_index(tt)
    bg = mu[tc][r]
    authoritative_lambda = authoritative_bg = authoritative_trigger = None
    try:
        # Replay the same boundary/gap state used in fitting.  This adds the
        # first-moment contribution of pre-history and events hidden in gaps;
        # the direct convolution below only covers imported observed events.
        trace = likelihood(
            params,
            scope,
            spec,
            fit["pspec"],
            fit["maps"],
            boundary=fit.get("boundary", "observed"),
            gap_correction=fit.get("gap_correction", True),
            want_grad=False,
            return_trace=True,
        )
        trace_row = trace["event_rows"][event_index]
        authoritative_lambda = float(trace_row["lambda"])
        authoritative_bg = float(trace_row["background"])
        authoritative_trigger = float(trace_row["trigger"])
        bg = authoritative_bg
    except Exception:
        pass

    rows = []
    source_totals = [0.0] * spec.k
    for j, e in enumerate(scope["events"]):
        if e["t"] >= tt:
            continue
        dt = tt - e["t"]
        if dt < 0:
            continue
        cj = e["ci"]
        b = beta[tc][cj]
        if spec.kernel_shape == "gamma2":
            val = eta[tc][cj] * b * b * dt * math.exp(-b * dt)
        else:
            val = eta[tc][cj] * b * math.exp(-b * dt)
        if val > 1e-12:
            rows.append(
                {
                    # Prepared events carry the stable imported-data index.
                    # Fall back to the scope position only for lightweight
                    # callers/tests that construct events without that field.
                    "event_index": e.get("index", j),
                    "scope_event_index": j,
                    "t": e["t"],
                    "category": e["category"],
                    "contribution": val,
                    "lag": dt,
                }
            )
            source_totals[cj] += val
    observed_trigger = sum(source_totals)
    if authoritative_trigger is not None:
        trigger = authoritative_trigger
        hidden_history_gap = max(0.0, authoritative_trigger - observed_trigger)
    else:
        trigger = observed_trigger
        hidden_history_gap = 0.0
    lam = authoritative_lambda if authoritative_lambda is not None else bg + trigger
    if lam <= 0:
        lam = 1e-12
    if hidden_history_gap > 1e-7 * lam:
        source_totals.append(hidden_history_gap)
        source_categories = list(fit["categories"]) + ["未记录历史/缺口期望"]
    else:
        source_categories = list(fit["categories"])
    unexplained = bg + hidden_history_gap
    rows.sort(key=lambda x: x["contribution"], reverse=True)
    top = rows[:top_n]
    for row in top:
        row["share_of_intensity"] = row["contribution"] / lam
        row["parent_probability"] = row["contribution"] / lam
    return {
        "event_index": event_index,
        "t": tt,
        "category": target_event["category"],
        "lambda": lam,
        "background": bg,
        "trigger": trigger,
        "unobserved_history_or_gap_trigger": hidden_history_gap,
        "unexplained_or_baseline": unexplained,
        "background_share": bg / lam,
        "trigger_share": trigger / lam,
        "source_totals": [{"category": source_categories[j], "contribution": v, "share": v / lam} for j, v in enumerate(source_totals)],
        "top_sources": top,
        "note": "贡献是模型条件强度分解；未记录历史/缺口期望不是某个可指认事件。父事件概率是归一化归因，不构成因果识别。",
    }



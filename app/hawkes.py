def simulate_forecast_counts(
    fit: Dict[str, Any],
    start: float,
    end: float,
    active_windows: Sequence[Tuple[float, float]],
    *,
    n_paths: int = 160,
    seed: int = 123,
    initial_state: Optional[Sequence[float]] = None,
) -> Dict[str, Any]:
    """Simulate future paths by multivariate thinning.

    The returned intervals are predictive intervals for counts recorded inside
    ``active_windows``.  Simulation is refused for supercritical branching
    matrices because no stationary long-run forecast exists.
    """
    rho = float(fit.get("rho", 1.0))
    if rho >= 0.999:
        return {
            "allowed": False,
            "reason": f"稳定性条件失败：rho(eta)={rho:.3f} >= 1；已拒绝长期推演。",
            "rho": rho,
        }
    params = fit["params"]
    model: ModelSpec = fit["spec"]
    maps = fit["maps"]
    mu, eta, beta = params["mu"], params["eta"], params["beta"]
    k = model.k
    base_state = list(initial_state) if initial_state is not None else fit.get("final_state")
    if base_state is None:
        base_state = [0.0] * model.state_size
    else:
        base_state = [float(x) for x in base_state]
    rng = random.Random(seed)
    wins = merge_windows([(float(a), float(b)) for a, b in active_windows])

    def active(t: float) -> bool:
        return any(a <= t < b for a, b in wins)

    all_counts: List[List[int]] = []
    category_counts: List[List[int]] = [[] for _ in range(k)]
    total_counts: List[int] = []
    for path in range(n_paths):
        m = list(base_state)
        cur = float(start)
        counts = [0] * k
        # If start is not exactly a window boundary, still simulate all actual
        # events through gaps; count only active intervals.
        while cur < end - 1e-10:
            r = model.bg_index(cur)
            lam = [mu[ci][r] + sum(m[ci * k + j] for j in range(k)) for ci in range(k)]
            upper = sum(lam)
            if model.kernel_shape == "gamma2":
                # Gamma(2) intensity state can rise after a jump as the cascade
                # transfers from y1 to y2.  y2(s) <= y2(0) + y1(0) for s>=0.
                n = k * k
                upper += sum(m[n + ai] for ai in range(n))
            if upper <= 1e-12:
                # No intensity except possible background jump at a cut.
                nxt = min([c for c in model.cuts if c > cur] + [end])
                cur = nxt
                continue
            # Background can only increase at the next cut.
            next_cut = min([c for c in model.cuts if c > cur + 1e-10] + [end])
            u = rng.random()
            dt = -math.log(max(u, 1e-12)) / upper
            cand = cur + dt
            if cand >= next_cut:
                _decay_state(m, None, next_cut - cur, beta, maps["beta"])
                cur = next_cut
                continue
            _decay_state(m, None, cand - cur, beta, maps["beta"])
            r2 = model.bg_index(cand)
            lam2 = [mu[ci][r2] + sum(m[ci * k + j] for j in range(k)) for ci in range(k)]
            total2 = sum(lam2)
            if rng.random() <= total2 / upper:
                pick = rng.random() * total2
                acc = 0.0
                ci = k - 1
                for ii, val in enumerate(lam2):
                    acc += val
                    if pick <= acc:
                        ci = ii
                        break
                if active(cand):
                    counts[ci] += 1
                _jump_event(ci, m, None, eta, beta, maps)
            cur = cand
        all_counts.append(counts)
        total_counts.append(sum(counts))
        for ci in range(k):
            category_counts[ci].append(counts[ci])

    def interval(xs: Sequence[float]) -> Dict[str, float]:
        ys = sorted(xs)
        return {
            "mean": sum(ys) / len(ys),
            "p05": quantile_sorted(ys, 0.05),
            "p25": quantile_sorted(ys, 0.25),
            "p50": quantile_sorted(ys, 0.5),
            "p75": quantile_sorted(ys, 0.75),
            "p95": quantile_sorted(ys, 0.95),
        }

    observed = [0] * k
    # Observed counts are supplied by caller comparison; here only paths.
    return {
        "allowed": True,
        "rho": rho,
        "n_paths": n_paths,
        "total": interval(total_counts),
        "categories": [interval(category_counts[ci]) for ci in range(k)],
        "paths_sample": all_counts[:20],
    }
